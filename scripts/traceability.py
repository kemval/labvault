"""
Build the validation documents from docs/validation/requirements.toml
(roadmap 5.5, ADR 0027): the requirements specification, the risk assessment
and the requirement -> ADR -> test traceability matrix.

    python scripts/traceability.py           # check, then write the documents
    python scripts/traceability.py --check   # check only; exit 1 if any problem
                                             # or a document is out of date

Checks: every requirement has a unique id, valid risk ratings and at least one
test; every test it names exists in tests/; every ADR it names exists.
tests/test_traceability.py runs --check, so CI fails on an untraced
requirement, a renamed test or a stale document.

DRAFT documents, not an executed validation: see docs/validation/validation-plan.md.
"""

import argparse
import ast
import os
import sys
import tomllib
from collections import defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "docs", "validation", "requirements.toml")
OUT_DIR = os.path.join(ROOT, "docs", "validation")
TESTS_DIR = os.path.join(ROOT, "tests")
ADR_DIR = os.path.join(ROOT, "docs", "adr")

RATINGS = ("H", "M", "L")
REQUIRED = ("id", "area", "title", "regulation", "impact", "likelihood",
            "detection", "controls", "adrs", "tests")

# GAMP 5 (2nd ed.), quality risk management: risk class from impact x likelihood,
# then priority from risk class x detectability.
RISK_CLASS = {
    ("H", "H"): 1, ("H", "M"): 1, ("H", "L"): 2,
    ("M", "H"): 1, ("M", "M"): 2, ("M", "L"): 3,
    ("L", "H"): 2, ("L", "M"): 3, ("L", "L"): 3,
}
PRIORITY = {
    (1, "L"): "High", (1, "M"): "High", (1, "H"): "Medium",
    (2, "L"): "High", (2, "M"): "Medium", (2, "H"): "Low",
    (3, "L"): "Medium", (3, "M"): "Low", (3, "H"): "Low",
}

BANNER = ("> **DRAFT — not an executed validation.** Generated by `scripts/traceability.py` "
          "from `docs/validation/requirements.toml`; edit that file, not this one. "
          "What a regulated lab must still do is in [the validation plan](validation-plan.md).\n")


def load(path=SOURCE):
    with open(path, "rb") as f:
        return tomllib.load(f).get("requirement", [])


def existing_tests(tests_dir=TESTS_DIR):
    """{"file.py::test_name"} for every test function in tests/."""
    found = set()
    for name in sorted(os.listdir(tests_dir)):
        if name.startswith("test_") and name.endswith(".py"):
            with open(os.path.join(tests_dir, name)) as f:
                tree = ast.parse(f.read(), name)
            found |= {f"{name}::{node.name}" for node in tree.body
                      if isinstance(node, ast.FunctionDef) and node.name.startswith("test_")}
    return found


def existing_adrs(adr_dir=ADR_DIR):
    """{"0001": "0001-deployment-modes.md", ...}"""
    return {name[:4]: name for name in os.listdir(adr_dir) if name[:4].isdigit()}


def problems(reqs, tests, adrs):
    """Every reason the requirements can't be traced, as readable lines."""
    found, seen = [], set()
    for i, r in enumerate(reqs):
        rid = r.get("id", f"requirement #{i + 1}")
        found += [f"{rid}: missing '{k}'" for k in REQUIRED if k not in r]
        if rid in seen:
            found.append(f"{rid}: duplicate id")
        seen.add(rid)
        found += [f"{rid}: {k} must be H, M or L" for k in ("impact", "likelihood", "detection")
                  if k in r and r[k] not in RATINGS]
        if not r.get("tests"):
            found.append(f"{rid}: no test traces this requirement")
        found += [f"{rid}: test not found: {t}" for t in r.get("tests", []) if t not in tests]
        found += [f"{rid}: ADR not found: {a}" for a in r.get("adrs", []) if a not in adrs]
    return found


def risk(r):
    cls = RISK_CLASS[(r["impact"], r["likelihood"])]
    return cls, PRIORITY[(cls, r["detection"])]


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def adr_links(r, adrs):
    return ", ".join(f"[{a}](../adr/{adrs[a]})" for a in r["adrs"]) or "—"


def render_specification(reqs):
    by_area = defaultdict(list)
    for r in reqs:
        by_area[r["area"]].append(r)
    out = ["# LabVault requirements specification\n", BANNER,
           f"{len(reqs)} requirements in {len(by_area)} areas. Each is traced to the automated "
           "tests that verify it in the [traceability matrix](traceability-matrix.md) and rated "
           "in the [risk assessment](risk-assessment.md).\n",
           "Scope: the LabVault application and its production container (ADR 0024), "
           "for managing QC samples, test results, reviews and OOS investigations.\n"]
    for area, items in by_area.items():
        out.append(f"## {area}\n")
        out.append("| ID | Requirement | Regulation |")
        out.append("|---|---|---|")
        out += [f"| {r['id']} | {cell(r['title'])} | {cell('; '.join(r['regulation']) or '—')} |"
                for r in items]
        out.append("")
    return "\n".join(out)


def render_risk(reqs):
    rated = [(r, *risk(r)) for r in reqs]
    counts = defaultdict(int)
    for _, _, priority in rated:
        counts[priority] += 1
    order = {"High": 0, "Medium": 1, "Low": 2}
    out = ["# LabVault risk assessment\n", BANNER,
           "Method: GAMP 5 (2nd ed.) quality risk management. For each requirement, the "
           "**impact** of a failure on product quality, patient safety or data integrity and "
           "its **likelihood** without the listed controls give the **risk class** (1 highest). "
           "The class and the **detectability** of a failure before harm give the **priority**, "
           "which sets how much verification a lab should require (see the validation plan).\n",
           "| Impact \\ Likelihood | L | M | H |", "|---|---|---|---|",
           *[f"| **{i}** | {RISK_CLASS[(i, 'L')]} | {RISK_CLASS[(i, 'M')]} | {RISK_CLASS[(i, 'H')]} |"
             for i in RATINGS],
           "",
           f"**Result:** {counts['High']} High, {counts['Medium']} Medium, {counts['Low']} Low "
           "priority. Ratings are the developer's draft and must be reviewed by the lab's QA.\n",
           "| ID | Requirement | Impact | Likelihood | Detection | Class | Priority | Controls |",
           "|---|---|---|---|---|---|---|---|"]
    for r, cls, priority in sorted(rated, key=lambda x: (order[x[2]], x[1], x[0]["id"])):
        out.append(f"| {r['id']} | {cell(r['title'])} | {r['impact']} | {r['likelihood']} | "
                   f"{r['detection']} | {cls} | **{priority}** | {cell(r['controls'])} |")
    return "\n".join(out) + "\n"


def render_matrix(reqs, adrs):
    traced = {t for r in reqs for t in r["tests"]}
    out = ["# LabVault traceability matrix\n", BANNER,
           f"Requirement → design decision (ADR) → automated tests. {len(reqs)} requirements, "
           f"{len(traced)} distinct tests traced (other tests cover supporting code, such as "
           "helpers and scripts). "
           "CI fails if a requirement has no test or names a test that no longer exists.\n",
           "Run the tests for one requirement: `pytest \"tests/<file>::<test>\"`.\n",
           "| ID | Requirement | Priority | ADRs | Tests |", "|---|---|---|---|---|"]
    for r in reqs:
        names = "<br>".join(f"`{t}`" for t in r["tests"])
        out.append(f"| {r['id']} | {cell(r['title'])} | {risk(r)[1]} | {adr_links(r, adrs)} | {names} |")
    return "\n".join(out) + "\n"


def documents(reqs, adrs):
    return {
        "requirements-specification.md": render_specification(reqs),
        "risk-assessment.md": render_risk(reqs),
        "traceability-matrix.md": render_matrix(reqs, adrs),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="only check; fail if a problem is found or a document is stale")
    args = parser.parse_args(argv)

    reqs, tests, adrs = load(), existing_tests(), existing_adrs()
    found = problems(reqs, tests, adrs)
    if found:
        print("Traceability problems:", *found, sep="\n  ", file=sys.stderr)
        return 1

    stale = []
    for name, text in documents(reqs, adrs).items():
        path = os.path.join(OUT_DIR, name)
        current = open(path).read() if os.path.exists(path) else None
        if current == text:
            continue
        if args.check:
            stale.append(name)
        else:
            with open(path, "w") as f:
                f.write(text)
            print(f"wrote docs/validation/{name}")
    if stale:
        print("Out of date (run python scripts/traceability.py):", *stale,
              sep="\n  ", file=sys.stderr)
        return 1
    print(f"Traceability ok: {len(reqs)} requirements, all traced to existing tests.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
